package day4;

public class SwitchCAse {

	public static void main(String[] args) {
		int Weekno=8;
		switch (Weekno) 
		{
		case 1:System.out.println("Sunady");
		break;
		case 2:System.out.println("mon");
		break;
		case 3:System.out.println("tue");
		break;
		case 4:System.out.println("wed");
		break;
		case 5:System.out.println("thur");break;
		case 6:System.out.println("fri");break;
		case 7:System.out.println("sat");break;
		default:System.out.println("Invalid week number");
		}

	}

}
